"""Generate independent RFC 1952 fixtures with Python's zlib; no neoCLR codec reuse."""
from pathlib import Path
import gzip
import struct
import zlib

small = b'abcabcabcabc'
large = (b'The quick brown fox jumps over the lazy dog. HTTP gzip content encoding.\n' * 40)
def member(data, level=6, strategy=zlib.Z_DEFAULT_STRATEGY):
    encoder = zlib.compressobj(level, zlib.DEFLATED, -15, strategy=strategy)
    return bytes.fromhex('1f8b08000000000000ff') + encoder.compress(data) + encoder.flush() + struct.pack('<II', zlib.crc32(data), len(data))
fixed = member(small, strategy=zlib.Z_FIXED)
dynamic = member(large)
assert (dynamic[10] >> 1) & 3 == 2
header = bytes.fromhex('1f8b081e0000000000ff') + b'\x03\x00abcname\x00comment\x00'
optional = header + struct.pack('<H', zlib.crc32(header) & 65535) + fixed[10:]
fixtures = dict(SmallData=small, LargeData=large, DoubleData=small * 2, Stored=member(small, 0), Fixed=fixed, Dynamic=dynamic, Optional=optional, Concatenated=fixed+fixed, Empty=member(b''), Bomb=member(b'A'*65537), Trailing=fixed+b'!', ReservedBlock=bytes.fromhex('1f8b08000000000000ff07'))
def invalid_deflate(fields):
    # Deliberately invalid RFC 1951 fields, packed least-significant bit first.
    value = width = 0
    raw = bytearray()
    for bits, count in fields:
        value |= bits << width
        width += count
        while width >= 8:
            raw.append(value & 255)
            value >>= 8
            width -= 8
    if width:
        raw.append(value & 255)
    return bytes.fromhex('1f8b08000000000000ff') + raw + bytes(8)
fixtures['EmptyCodeTree'] = invalid_deflate([(5,3),(0,5),(0,5),(0,4)] + [(0,3)]*4)
fixtures['ReservedLiteral'] = invalid_deflate([(3,3),(99,8)])  # Fixed symbol 286.
fixtures['MissingHistory'] = invalid_deflate([(3,3),(64,7),(0,5),(0,7)])  # Length 3, distance 1 before output.
for name in ('Stored','Fixed','Dynamic','Optional','Concatenated','Empty'):
    assert gzip.decompress(fixtures[name]) == {'Dynamic':large, 'Concatenated':small*2, 'Empty':b''}.get(name,small)
lines=['// Generated by generate-fixtures.py using independent Python/zlib gzip data.', 'module NeoClr.RuntimeTests', '', 'import System.*', '']
for name,data in fixtures.items():
    if name == 'LargeData':
        lines += ['func LargeData() -> byte[] {', '    let data: byte[] = [for unused in 0..<'+str(len(data))+' => (byte)0]', '    let pattern: byte[] = ['+','.join('(byte)'+str(b) for b in large[:len(large)//40])+']', '    var index = 0', '    while index < data.Length {', '        data[index] = pattern[index % pattern.Length]', '        index += 1', '    }', '    return data', '}', '']
        continue
    lines += ['func '+name+'() -> byte[] {', '    return [']
    for start in range(0,len(data),16):
        lines.append('        '+', '.join('(byte)'+str(b) for b in data[start:start+16])+(',' if start+16<len(data) else ''))
    lines += ['    ]','}', '']
Path(__file__).with_name('Fixtures.rvn').write_text('\n'.join(lines))
