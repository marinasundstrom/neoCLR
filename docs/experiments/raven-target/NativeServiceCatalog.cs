using System.Text;
using System.Text.Json;

// One signature inventory serves legacy translation and native bootstrap authoring.
// Selection is explicit; declarations never imply an unimplemented runtime service.
static partial class RuntimeServiceBindings
{
    static readonly string[] NativeSelection = [
        "StringHashOrdinalIgnoreCase", "SystemCultureName", "UnixTimeTicks", "UnixTimeToLocal", "ParseInt64",
        "Utf8Encode", "Utf8Decode", "FileOpenRead", "FileCreateNew", "FilePosition", "FileSeek",
        "FileReadInto", "FileWriteChunk", "FileFlush", "FileClose", "StartWorker", "QueueWorker",
        "JoinWorker", "RequestWorkerCancellation", "JoinWorkerResult", "ScheduleTask", "DrainEntryTasks"
    ];

    static string Category(string type) => type switch
    {
        "noresult" => "no-result",
        "Value" => "erased-value",
        "System.RuntimeTypeHandle" or "IntPtr" or "UIntPtr" => "opaque-handle",
        _ when type.StartsWith("arrayref<", StringComparison.Ordinal) => "vector",
        _ when type.StartsWith("fn<", StringComparison.Ordinal) => "callback",
        _ when type.StartsWith("System.", StringComparison.Ordinal) => "nominal",
        _ => "scalar"
    };

    static bool NativeTypeSupported(string type) => type is "String" or "Int32" or "Int64" or "Boolean" or "Byte" or "Value" or "noresult"
        or "arrayref<Byte>" or "arrayref<Int32>" or "fn<String,String>" or "fn<noresult Void>";

    static (string Name, string[] Args, string Result)[] NativeMembers(string[]? selection = null)
    {
        selection ??= NativeSelection;
        if (selection.Distinct(StringComparer.Ordinal).Count() != selection.Length)
            throw new InvalidDataException("Duplicate native service selection.");
        return selection.Select(name =>
        {
            var entries = Members.Where(m => m.Name == name).ToArray();
            if (entries.Length != 1) throw new InvalidDataException("Missing or ambiguous native service: " + name);
            var entry = entries[0];
            // CLI Action transports an explicit no-result callback, not an inhabited Void return.
            entry.Args = entry.Args.Select(t => t == "fn<Void>" ? "fn<noresult Void>" : t).ToArray();
            if (name == "NotifyWorker" || !NativeTypeSupported(entry.Result) || entry.Args.Any(t => t == "noresult" || !NativeTypeSupported(t)) || IsProperty(name))
                throw new InvalidDataException("Unsupported native bootstrap service signature: " + name);
            return entry;
        }).ToArray();
    }

    static string NativeCSharp(string type) => type == "fn<noresult Void>" ? "System.Action" : CSharp(type);
    internal static string NativeBootstrapDeclarations =>
        "namespace System.Runtime.CompilerServices { public static class RuntimeServices { " +
        string.Join(" ", NativeMembers().Select(m => $"public static {NativeCSharp(m.Result)} {m.Name}({string.Join(',', m.Args.Select((t, i) => NativeCSharp(t) + " arg" + i))}) " +
            (m.Result == "noresult" ? "{ }" : "=> default;"))) +
        " public static bool IsValue<T>(System.Value value) => false; public static T UnpackValue<T>(System.Value value) => default; } }";

    internal static string NativeBootstrapSeed()
    {
        var text = new StringBuilder("; Generated by Probe --native-service-catalog. Do not edit.\n.type System.Runtime.CompilerServices.RuntimeServices\n");
        text.Append(".method static IsValue<T>(Value value) -> Boolean\nldarg value\nvalue.is T\nret\n.end\n");
        text.Append(".method static UnpackValue<T>(Value value) -> T\nldarg value\nvalue.unpack T\nret\n.end\n");
        foreach (var member in NativeMembers())
        {
            var parameters = string.Join(',', member.Args.Select((t, i) => t + " arg" + i));
            text.AppendLine($".method static {member.Name}({parameters}) -> {member.Result}");
            var vector = member.Result.StartsWith("arrayref<", StringComparison.Ordinal);
            var element = vector ? member.Result[9..^1] : "";
            if (vector)
                text.AppendLine($".local {element}[] source\n.local {member.Result} destination\n.local Int32 index");
            for (int i = 0; i < member.Args.Length; i++) text.AppendLine("ldarg arg" + i);
            text.AppendLine($"call neoCLR.Runtime.{member.Name}({string.Join(',', member.Args)})");
            if (member.Result == "noresult") text.AppendLine("pop");
            if (vector)
                text.AppendLine($"stloc source\nldloc source\nldlen\nconv.i4\nnewarr {element}\nstloc destination\nldc.i4 0\nstloc index\nbr Test\nCopy:\nldloc destination\nldloc index\nldloc source\nldloc index\nldelem {element}\nstelem {element}\nldloc index\nldc.i4 1\nadd\nstloc index\nTest:\nldloc index\nldloc source\nldlen\nconv.i4\nblt Copy\nldloc destination");
            text.AppendLine("ret\n.end");
        }
        text.AppendLine(".end");
        foreach (var member in NativeMembers())
        {
            // String hashing is already required by the primitive string seed.
            if (member.Name == "StringHashOrdinalIgnoreCase") continue;
            var nativeResult = member.Result == "noresult" ? "Void" : member.Result.StartsWith("arrayref<", StringComparison.Ordinal) ? member.Result[9..^1] + "[]" : member.Result;
            text.AppendLine($".function neoCLR.Runtime.{member.Name}({string.Join(',', member.Args.Select((t, i) => t + " arg" + i))}) -> {nativeResult}\n.methodimpl InternalCall\n.end");
        }
        text.AppendLine(".type System.Value\n.sealed\n.end");
        return text.ToString();
    }

    internal static void CheckNativeCatalog()
    {
        _ = NativeMembers();
        foreach (var selection in new[] { new[] { "Missing" }, new[] { "MathSqrt" }, new[] { "NotifyWorker" }, new[] { "CurrentTaskQueue" }, new[] { "ParseInt64", "ParseInt64" } })
        {
            bool rejected = false;
            try { _ = NativeMembers(selection); } catch (InvalidDataException) { rejected = true; }
            if (!rejected) throw new Exception("Native service catalog accepted an invalid selection.");
        }
        Console.WriteLine("PASS native service catalog selection, missing/duplicate identities and unsupported numeric/nominal shapes");
    }

    internal static void WriteNativeCatalog(string directory)
    {
        Directory.CreateDirectory(directory);
        var selected = NativeMembers().Select(m => m.Name).ToHashSet(StringComparer.Ordinal);
        var inventory = Members.Select(m => new
        {
            name = m.Name,
            arguments = m.Args,
            result = m.Result,
            categories = m.Args.Append(m.Result).Select(Category).Distinct().Order().ToArray(),
            nativeBootstrap = selected.Contains(m.Name),
            implementation = m.Name is "LocalDateTime" or "TypeInfo" ? "source-factory-alias" : "requires-explicit-binding"
        }).ToArray();
        File.WriteAllText(Path.Combine(directory, "service-catalog.json"), JsonSerializer.Serialize(new { version = 1, services = inventory }, new JsonSerializerOptions { WriteIndented = true }) + "\n");
        File.WriteAllText(Path.Combine(directory, "service-seed.neoil"), NativeBootstrapSeed());
    }
}
