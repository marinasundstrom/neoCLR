#!/usr/bin/env python3
"""Inventory authored public Raven types; not a compiler or execution qualifier.

The repository convention is top-level public declarations. Mask comments/literals
and inspect only immediate type members, so nested helpers cannot lend contracts
to their enclosing type. --check detects inventory drift; semantic review is manual.
"""
import argparse
from collections import Counter
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'docs/design/class-library-type-inventory-20261020.md'
DECL = re.compile(r'^public\s+((?:(?:sealed|abstract|open|static|ref|record)\s+)*)(class|struct|interface|union|enum)\s+(\w+)', re.M)
MASK = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'')
PRIMITIVES = set('Boolean Byte SByte Int16 UInt16 Int32 UInt32 Int64 UInt64 IntPtr UIntPtr Single Double Char RuntimeTypeHandle Void Value'.split())

def inspect(path):
    original = path.read_text()
    text = MASK.sub(lambda m: ''.join('\n' if c == '\n' else ' ' for c in m[0]), original)
    module = re.search(r'^module\s+(\S+)', text, re.M)
    if module is None:
        return  # Assembly-only attribute files declare no public types.
    namespace = module[1]
    for match in DECL.finditer(text):
        mods, kind, name = match.groups()
        start = match.end()
        # Headers may span lines (positional records). Parentheses/generic brackets
        # belong to the header; stop at the first body or a balanced newline.
        level = 0
        end = start
        while end < len(text):
            c = text[end]
            if c in '(<': level += 1
            elif c in ')>': level -= 1
            if c == '{' or (c == '\n' and level == 0): break
            end += 1
        header = original[match.start():end].strip().replace('\n', ' ')
        body = ''
        if end < len(text) and text[end] == '{':
            depth = 1
            cursor = end + 1
            while cursor < len(text) and depth:
                c = text[cursor]
                if c == '{': depth += 1
                if c == '}': depth -= 1
                cursor += 1
            # Keep only declaration starts at depth 1, including method lines
            # whose opening brace moves depth to 2 before their newline.
            body_chars = []
            depth = 1
            for c in text[end + 1:cursor - 1]:
                body_chars.append(c if depth == 1 or c == '\n' else ' ')
                if c == '{': depth += 1
                if c == '}': depth -= 1
            body = ''.join(body_chars)
        members = []
        for meth in re.finditer(r'^\s*((?:(?:override|virtual|static|private|internal|public)\s+)*)func\s+(Equals|GetHashCode|ToString)\s*\(([^)]*)\)', body, re.M):
            modifiers, method, args = meth.groups()
            if 'static' in modifiers or 'private' in modifiers: continue
            if method == 'Equals':
                if ',' in args: continue  # comparer policy, not the receiver's equality
                tag = 'Eo' if re.search(r':\s*(?:System\.)?Object\??', args) else 'Et'
            elif method == 'GetHashCode':
                if args.strip(): continue
                tag = 'H'
            else:
                tag = 'T' if not args.strip() else 'Tf'
            members.append(tag + ('*' if 'override' in modifiers else ''))
        if kind == 'interface': family = 'Contract'
        elif 'static' in mods: family = 'Static'
        elif kind == 'enum': family = 'Enum'
        elif kind == 'union': family = 'Union'
        elif 'record' in mods: family = 'Record'
        elif 'ref' in mods: family = 'Borrowed view'
        elif namespace == 'System' and name in ('Memory', 'ReadOnlyMemory'): family = 'Owned view'
        elif namespace == 'System' and name in PRIMITIVES: family = 'Intrinsic'
        elif kind == 'struct': family = 'Value'
        elif 'Eo*' in members: family = 'Reference value'
        else: family = 'Reference'
        yield dict(name=namespace + '.' + name, path=path.relative_to(ROOT).as_posix(),
                   line=original.count('\n', 0, match.start()) + 1,
                   kind=family, members=', '.join(dict.fromkeys(members)) or '—', header=header)

def inventory():
    rows = []
    for parent, pattern in (('runtime', 'System.*'), ('extensions', 'Neo.*')):
        for project in sorted((ROOT / parent).glob(pattern)):
            for path in sorted((project / 'src').rglob('*.rvn')):
                if not {'bin', 'obj', 'core', 'native'}.intersection(path.relative_to(project).parts):
                    rows.extend(inspect(path))
    rows.sort(key=lambda r: (r['name'], r['header']))
    return rows

def render():
    rows = inventory()
    counts = Counter(r['kind'] for r in rows)
    out = ['# Public type contract inventory — 2026-10-20', '',
           'Generated by `python3 scripts/audit-type-contracts.py`; verify with `--check`.',
           'Scope: every top-level public type declaration in `runtime/System.*/src` and',
           '`extensions/Neo.*/src`, including the optional PostgreSQL provider. This is',
           'a source contract inventory, **not** proof of execution support or API metadata parity.',
           'Compiler-generated carriers, module functions and internal helpers are not counted.',
           'See the [review and findings](class-library-soundness-20261020.md#whole-library-contract-pass) for manual interpretation,',
           'inherited/runtime contracts, execution evidence, allocation concerns and remaining gaps.', '',
           f'**{len(rows)} declarations**: ' + '; '.join(f'{k}: {v}' for k,v in sorted(counts.items())) + '.', '',
           '`Et` = typed Equals; `Eo` = Object Equals; `H` = parameterless GetHashCode;',
           '`T` = parameterless ToString; `Tf` = formatted ToString overload; `*` = authored override.',
           'Only immediate declared members appear. A dash means inherited/generated/runtime behavior,',
           'not missing semantics. Comparer callbacks are policies for arguments, not receiver equality.',
           'Reference subclasses may inherit value contracts (notably IPv4Address/IPv6Address).', '',
           '| Type / source | Family | Declared equality, hash, display |',
           '| --- | --- | --- |']
    for r in rows:
        # Duplicate names differ by arity (Task and Task<T>); display full generic header name.
        name = re.search(r'\b(?:class|struct|interface|union|enum)\s+(\w+(?:<[^>]+>)?)', r['header'])[1]
        full = r['name'].rsplit('.',1)[0] + '.' + name
        out.append(f"| [{full}](../../{r['path']}#L{r['line']}) | {r['kind']} | {r['members']} |")
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--native-site', type=Path, help='Check a freshly rendered native site has a type page for every source declaration')
    args = parser.parse_args()
    result = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('Type inventory is stale; regenerate and review changed contracts.')
        print('Public type contract inventory matches source.')
    else:
        OUTPUT.write_text(result)
        print(OUTPUT.relative_to(ROOT))
    if args.native_site:
        missing = []
        rows = inventory()
        for row in rows:
            name = re.search(r'\b(?:class|struct|interface|union|enum)\s+(\w+)(?:<([^>]+)>)?', row['header'])
            short = name[1] + ('`' + str(name[2].count(',') + 1) if name[2] else '')
            namespace = row['name'].rsplit('.', 1)[0].lower().replace('.', '/')
            page = args.native_site / 'docs/api' / namespace / short / 'index.html'
            if not page.is_file(): missing.append(str(page))
        if missing:
            raise SystemExit('Native type pages missing:\n' + '\n'.join(missing))
        print(f'Mapped {len(rows)} public declarations to native API type pages; not member-signature parity proof.')
