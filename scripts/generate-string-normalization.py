#!/usr/bin/env python3
"""Generate pinned Unicode 17 canonical decomposition/ordering and conformance cases.
Usage: generate-string-normalization.py DIRECTORY
Inputs: https://www.unicode.org/Public/17.0.0/ucd/{UnicodeData,NormalizationTest}.txt
Normal builds use checked-in outputs, with no network or host Unicode dependency.
"""
import hashlib
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
hashes = {
    'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
    'NormalizationTest.txt': '5019ffd530751a741900c849c0e010332f142a3612234639bd200b82138a87db',
}
inputs = {}
for name, expected in hashes.items():
    raw = (Path(sys.argv[1]) / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected:
        raise SystemExit(f'{name} does not match pinned Unicode 17.0.0 SHA-256')
    inputs[name] = raw.decode()
raw_decomposition, combining = {}, []
for line in inputs['UnicodeData.txt'].splitlines():
    fields = line.split(';')
    scalar = int(fields[0], 16)
    if int(fields[3]):
        combining.append((scalar, int(fields[3])))
    if fields[5] and not fields[5].startswith('<'):
        raw_decomposition[scalar] = [int(x, 16) for x in fields[5].split()]


def decompose(scalar, active=()):
    assert scalar not in active, 'cyclic canonical decomposition'
    if scalar not in raw_decomposition:
        return [scalar]
    return [item for child in raw_decomposition[scalar]
            for item in decompose(child, (*active, scalar))]


mappings = [(scalar, decompose(scalar)) for scalar in sorted(raw_decomposition)]
assert max(len(value) for _, value in mappings) <= 4
lines = [
    '// Generated by scripts/generate-string-normalization.py; do not edit.',
    '// Unicode 17.0.0 UnicodeData.txt SHA-256 ' + hashes['UnicodeData.txt'],
    '// Unicode data license: ../third-party/unicode/LICENSE.txt',
    '// Recursively expanded canonical mappings only; Hangul is decomposed algorithmically.',
    'pub(crate) const DECOMPOSITION: &[(u32, &[u32])] = &[',
]
lines += [f'    (0x{scalar:04X}, &[{", ".join(f"0x{x:04X}" for x in value)}]),'
          for scalar, value in mappings]
lines += ['];', 'pub(crate) const COMBINING: &[(u32, u8)] = &[']
lines += [f'    (0x{scalar:04X}, {value}),' for scalar, value in combining]
lines += ['];', '']
(root / 'src/string_normalization_data.rs').write_text('\n'.join(lines))
cases = ['# Unicode 17.0.0 NormalizationTest.txt, first five conformance columns.',
         '# Original SHA-256 ' + hashes['NormalizationTest.txt'],
         '# Unicode data license: ../../third-party/unicode/LICENSE.txt']
for line in inputs['NormalizationTest.txt'].splitlines():
    text = line.split('#', 1)[0].strip()
    if text and not text.startswith('@'):
        cases.append(';'.join(x.strip() for x in text.split(';')[:5]))
destination = root / 'tests/fixtures/normalization-17.txt'
destination.parent.mkdir(exist_ok=True)
destination.write_text('\n'.join(cases) + '\n')
print(f'{len(mappings)} mappings; {len(combining)} combining classes; {len(cases)-3} conformance rows')
